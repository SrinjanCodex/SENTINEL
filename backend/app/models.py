"""
SENTINEL — SQLAlchemy Data Models
Defines relational models for Reports, Incidents, Junction Links, Evidence,
Verification Records, Priority Assessments, and Missing Signals.
"""
import uuid
from datetime import datetime, timezone
from sqlalchemy import (
    Column,
    String,
    Text,
    Float,
    Integer,
    Boolean,
    DateTime,
    ForeignKey,
    JSON,
)
from sqlalchemy.orm import relationship
from app.database import Base


def generate_uuid() -> str:
    """Generates a random UUID string."""
    return str(uuid.uuid4())


def utc_now() -> datetime:
    """Returns current UTC timestamp with timezone."""
    return datetime.now(timezone.utc)


class Report(Base):
    """
    Community waterlogging report.
    original_description is immutable once created.
    """
    __tablename__ = "reports"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    original_description = Column(Text, nullable=False)
    category = Column(String(50), nullable=False, default="uncertain")
    category_confidence = Column(Float, nullable=True)
    category_uncertain = Column(Boolean, nullable=False, default=True)
    reported_severity = Column(Integer, nullable=True)
    address = Column(Text, nullable=True)
    latitude = Column(Float, nullable=True)
    longitude = Column(Float, nullable=True)
    observed_at = Column(DateTime(timezone=True), nullable=True)
    submitted_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)
    status = Column(String(30), nullable=False, default="unverified")
    photo_reference = Column(String(255), nullable=True)
    reporter_token = Column(String(64), nullable=False, default=generate_uuid)
    is_synthetic = Column(Boolean, nullable=False, default=False)
    updated_at = Column(DateTime(timezone=True), nullable=False, default=utc_now, onupdate=utc_now)

    # Relationships
    incident_links = relationship("IncidentReport", back_populates="report", cascade="all, delete-orphan")
    analysis = relationship("ReportAnalysis", back_populates="report", uselist=False, cascade="all, delete-orphan")


class Incident(Base):
    """
    Potential Incident hypothesis generated by clustering reports.
    Placeholder in Milestone 2 until automated clustering is connected in Milestone 4.
    """
    __tablename__ = "incidents"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    title = Column(String(255), nullable=False)
    centroid_latitude = Column(Float, nullable=True)
    centroid_longitude = Column(Float, nullable=True)
    first_observed_at = Column(DateTime(timezone=True), nullable=True)
    last_observed_at = Column(DateTime(timezone=True), nullable=True)
    verification_status = Column(String(50), nullable=False, default="suspected")
    created_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)
    last_analysed_at = Column(DateTime(timezone=True), nullable=True)
    analysis_version = Column(String(20), nullable=False, default="1.0.0")
    priority_score = Column(Float, nullable=True)

    # Relationships
    report_links = relationship("IncidentReport", back_populates="incident", cascade="all, delete-orphan")
    evidence_items = relationship("Evidence", back_populates="incident", cascade="all, delete-orphan")
    verification_records = relationship("VerificationRecord", back_populates="incident", cascade="all, delete-orphan")
    missing_signals = relationship("MissingSignal", back_populates="incident", cascade="all, delete-orphan")
    priority_assessment = relationship("PriorityAssessment", back_populates="incident", uselist=False, cascade="all, delete-orphan")


class IncidentReport(Base):
    """
    Junction record linking a Report to a candidate Incident.
    """
    __tablename__ = "incident_reports"

    id = Column(Integer, primary_key=True, autoincrement=True)
    incident_id = Column(String(36), ForeignKey("incidents.id", ondelete="CASCADE"), nullable=False)
    report_id = Column(String(36), ForeignKey("reports.id", ondelete="CASCADE"), nullable=False)
    match_score = Column(Float, nullable=True)
    match_reasons = Column(JSON, nullable=True)
    is_independent = Column(Boolean, nullable=False, default=True)
    added_by = Column(String(50), nullable=False, default="system")
    created_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)

    incident = relationship("Incident", back_populates="report_links")
    report = relationship("Report", back_populates="incident_links")


class Evidence(Base):
    """
    Structured piece of evidence supporting or contradicting an incident hypothesis.
    """
    __tablename__ = "evidence"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    incident_id = Column(String(36), ForeignKey("incidents.id", ondelete="CASCADE"), nullable=False)
    type = Column(String(50), nullable=False)
    description = Column(Text, nullable=False)
    provenance_source = Column(String(255), nullable=False)
    provenance_url = Column(String(500), nullable=True)
    observed_at = Column(DateTime(timezone=True), nullable=True)
    retrieved_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)
    kind = Column(String(50), nullable=False, default="observation")
    supports = Column(Boolean, nullable=False, default=True)
    is_synthetic = Column(Boolean, nullable=False, default=False)

    incident = relationship("Incident", back_populates="evidence_items")


class VerificationRecord(Base):
    """
    Audit log of human inspection verifications or system state transitions.
    """
    __tablename__ = "verification_records"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    incident_id = Column(String(36), ForeignKey("incidents.id", ondelete="CASCADE"), nullable=False)
    previous_status = Column(String(50), nullable=False)
    new_status = Column(String(50), nullable=False)
    changed_by = Column(String(100), nullable=False, default="system")
    timestamp = Column(DateTime(timezone=True), nullable=False, default=utc_now)
    note = Column(Text, nullable=False)

    incident = relationship("Incident", back_populates="verification_records")


class PriorityAssessment(Base):
    """
    Scoring breakdown and factors (Placeholder for Milestone 5).
    """
    __tablename__ = "priority_assessments"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    incident_id = Column(String(36), ForeignKey("incidents.id", ondelete="CASCADE"), unique=True, nullable=False)
    score = Column(Float, nullable=False)
    factors = Column(JSON, nullable=True)
    formula_version = Column(String(20), nullable=False, default="1.0.0")
    computed_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)

    incident = relationship("Incident", back_populates="priority_assessment")


class MissingSignal(Base):
    """
    Flagged evidence gap or missing confirmation signal (Placeholder for Milestone 5).
    """
    __tablename__ = "missing_signals"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    incident_id = Column(String(36), ForeignKey("incidents.id", ondelete="CASCADE"), nullable=False)
    rule_id = Column(String(50), nullable=False)
    severity = Column(String(20), nullable=False, default="medium")
    explanation = Column(Text, nullable=False)
    recommended_action = Column(Text, nullable=False)
    computed_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)

    incident = relationship("Incident", back_populates="missing_signals")


class ReportAnalysis(Base):
    """
    Automated NLP & heuristic analysis result for a single report.
    Stores predicted severity, extraction details, detected duplicates, and confidence.
    """
    __tablename__ = "report_analysis"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    report_id = Column(String(36), ForeignKey("reports.id", ondelete="CASCADE"), unique=True, nullable=False, index=True)
    severity = Column(String(20), nullable=True)             # low / moderate / high / critical
    severity_confidence = Column(Float, nullable=True)        # 0.0 - 1.0 probability
    all_scores = Column(JSON, nullable=True)                 # dict of all class probabilities
    confidence_score = Column(Float, nullable=True)           # composite 0.0 - 1.0 confidence
    confidence_reason = Column(Text, nullable=True)          # explanatory text
    extracted_locations = Column(JSON, nullable=True)        # list of string location hints
    extracted_depth = Column(String(50), nullable=True)      # e.g. "30 cm", "knee-deep"
    extracted_times = Column(JSON, nullable=True)            # list of time hints
    possible_duplicates = Column(JSON, nullable=True)        # list of {id, text, similarity}
    embedding_provider = Column(String(50), nullable=True)   # "sentence-transformers" | "tfidf"
    analysed_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)

    report = relationship("Report", back_populates="analysis")
